import logging
from datetime import UTC, datetime

from arq import Retry
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models import PullRequest, Repository, Review, ReviewComment
from app.db.session import AsyncSessionLocal
from app.services.github_client import get_github_client
from app.services.llm_reviewer import ReviewCommentOut, get_llm_reviewer

logger = logging.getLogger(__name__)

# Total attempts per job (1 initial + retries). Mirrored in WorkerSettings.max_tries.
MAX_TRIES = 3
RETRY_BASE_DELAY_SECONDS = 10


async def _get_or_create_repo(
    session: AsyncSession, github_repo_id: int, full_name: str
) -> Repository:
    result = await session.execute(
        select(Repository).where(Repository.github_repo_id == github_repo_id)
    )
    repo = result.scalar_one_or_none()
    if repo is None:
        repo = Repository(github_repo_id=github_repo_id, full_name=full_name)
        session.add(repo)
        await session.flush()
    return repo


async def _get_or_create_pr(
    session: AsyncSession,
    repo: Repository,
    number: int,
    head_sha: str,
    title: str,
) -> PullRequest:
    result = await session.execute(
        select(PullRequest).where(
            PullRequest.repository_id == repo.id,
            PullRequest.number == number,
            PullRequest.head_sha == head_sha,
        )
    )
    pr = result.scalar_one_or_none()
    if pr is None:
        pr = PullRequest(
            repository_id=repo.id,
            number=number,
            head_sha=head_sha,
            title=title,
        )
        session.add(pr)
        await session.flush()
    return pr


async def _get_or_create_review(
    session: AsyncSession, pr: PullRequest, review_id: int | None
) -> Review:
    """Reuse an existing review row instead of creating duplicates.

    - review_id given (manual retry API): reuse that row.
    - otherwise reuse an unfinished (queued/running) review of this PR+SHA,
      which is what an automatic arq retry of the same job will find.
    """
    if review_id is not None:
        review = await session.get(Review, review_id)
        if review is None:
            raise RuntimeError(f"Review {review_id} not found")
        return review

    result = await session.execute(
        select(Review)
        .where(
            Review.pull_request_id == pr.id,
            Review.status.in_(("queued", "running")),
        )
        .order_by(Review.id.desc())
        .limit(1)
    )
    review = result.scalar_one_or_none()
    if review is None:
        review = Review(pull_request_id=pr.id, status="queued")
        session.add(review)
        await session.flush()
    return review


def _format_github_body(summary: str, comments: list[ReviewCommentOut]) -> str:
    lines = ["## AI Code Review", "", summary, ""]
    if comments:
        lines.append("### Comments")
        for c in comments:
            loc = c.file_path or "?"
            if c.line is not None:
                loc = f"{loc}:{c.line}"
            lines.append(f"- **[{c.severity}]** `{loc}` — {c.body}")
        lines.append("")
    lines.append("---")
    lines.append("_Generated by PR Review Assistant_")
    return "\n".join(lines)


async def _post_to_github(
    github, full_name: str, pr_number: int, summary: str, comments: list[ReviewCommentOut]
) -> None:
    """Post line comments as a PR review; fall back to a single issue comment.

    GitHub rejects the whole review (422) if any line comment points outside the diff,
    so on failure we still leave one summary comment on the PR.
    """
    body = _format_github_body(summary, comments)
    line_comments = [
        {"path": c.file_path, "line": c.line, "body": f"**[{c.severity}]** {c.body}"}
        for c in comments
        if c.file_path and c.line is not None
    ]
    if line_comments:
        try:
            await github.create_pull_review(
                full_name,
                pr_number,
                body=summary or "AI review",
                event="COMMENT",
                comments=line_comments,
            )
            return
        except Exception as exc:
            logger.warning("Line-comment review rejected, falling back to issue comment: %s", exc)
    await github.create_issue_comment(full_name, pr_number, body)


async def run_review(
    ctx: dict,
    github_repo_id: int,
    full_name: str,
    pr_number: int,
    head_sha: str,
    title: str = "",
    review_id: int | None = None,
) -> dict:
    """Full pipeline: review row → fetch diff → LLM → save → comment on PR.

    On failure the job is retried (arq ``Retry``) up to MAX_TRIES with linear backoff,
    reusing the same review row. After the last attempt the review is marked failed.
    """
    job_try: int = ctx.get("job_try", 1)
    logger.info(
        "run_review start: repo=%s pr=%s sha=%s try=%s",
        full_name,
        pr_number,
        head_sha[:7] if head_sha else "",
        job_try,
    )

    async with AsyncSessionLocal() as session:
        try:
            repo = await _get_or_create_repo(session, github_repo_id, full_name)
            pr = await _get_or_create_pr(session, repo, pr_number, head_sha, title)
            review = await _get_or_create_review(session, pr, review_id)
            review.status = "running"
            review.error = None
            review.finished_at = None
            await session.commit()
            review_id = review.id
            logger.info("Review %s marked running (pr_id=%s)", review_id, pr.id)
        except Exception:
            await session.rollback()
            logger.exception("Failed to prepare review record")
            raise

    # --- external I/O outside the first transaction ---
    try:
        github = get_github_client()
        llm = get_llm_reviewer()

        diff = await github.get_pull_diff(full_name, pr_number)
        result = await llm.review(diff)

        async with AsyncSessionLocal() as session:
            review = await session.get(Review, review_id)
            if review is None:
                raise RuntimeError(f"Review {review_id} disappeared")

            review.summary = result.summary
            review.model = result.model
            review.input_tokens = result.input_tokens
            review.output_tokens = result.output_tokens
            for c in result.comments:
                session.add(
                    ReviewComment(
                        review_id=review.id,
                        file_path=c.file_path,
                        line=c.line,
                        severity=c.severity,
                        body=c.body,
                    )
                )

            # Review data is the source of truth; a GitHub posting failure is logged,
            # not fatal (re-running the LLM would only cost tokens and duplicate rows).
            try:
                await _post_to_github(github, full_name, pr_number, result.summary, result.comments)
            except Exception as gh_err:
                logger.warning("GitHub comment failed (review kept): %s", gh_err)

            review.status = "done"
            review.finished_at = datetime.now(UTC)
            await session.commit()

        logger.info(
            "Review %s done: %d comments, tokens in=%s out=%s",
            review_id,
            len(result.comments),
            result.input_tokens,
            result.output_tokens,
        )
        return {"review_id": review_id, "status": "done", "comments": len(result.comments)}

    except Exception as exc:
        final = job_try >= MAX_TRIES
        logger.exception(
            "run_review failed for review_id=%s (try %s/%s)", review_id, job_try, MAX_TRIES
        )
        async with AsyncSessionLocal() as session:
            review = await session.get(Review, review_id)
            if review is not None:
                review.error = str(exc)[:2000]
                if final:
                    review.status = "failed"
                    review.finished_at = datetime.now(UTC)
                else:
                    review.status = "queued"
                await session.commit()

        if not final:
            raise Retry(defer=RETRY_BASE_DELAY_SECONDS * job_try) from exc
        return {"review_id": review_id, "status": "failed", "error": str(exc)[:200]}
